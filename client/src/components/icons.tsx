export function Icon({
  name,
  size = 20,
  className = '',
  strokeWidth = 1.8,
}: {
  name: IconName
  size?: number
  className?: string
  strokeWidth?: number
}) {
  if (BRAND[name]) {
    return (
      <svg width={size} height={size} viewBox="0 0 24 24" fill="currentColor" className={className}>
        <path d={BRAND[name]} />
      </svg>
    )
  }
  const paths = UI[name] || UI.globe
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
    >
      {paths.map((d, i) => (
        <path key={i} d={d} />
      ))}
    </svg>
  )
}

export function platformIcon(name: string): IconName {
  const n = name.toLowerCase()
  if (n.includes('github')) return 'github'
  if (n === 'x' || n.includes('twitter')) return 'x'
  if (n.includes('weibo')) return 'weibo'
  if (n.includes('bili')) return 'bilibili'
  if (n.includes('xiaohongshu') || n.includes('red')) return 'xiaohongshu'
  if (n.includes('linkedin')) return 'linkedin'
  if (n.includes('mail') || n.includes('email')) return 'mail'
  if (n.includes('rss')) return 'rss'
  return 'globe'
}

